#!/usr/bin/env python3
from __future__ import annotations

"""
Phase 0 – AI test selection script.

Given a git diff (via --base/--head or --diff-file), calls Azure OpenAI to select
which Playwright E2E tests (discovered via glob under Worklist-2/playwright) should run.
Outputs selected paths and the npx playwright test ... command.

Usage (from E2E-Affected-Tests-POC or scripts/):
  python select_tests.py --repo ../OmegaAI-Mono --base master --head HEAD
  python select_tests.py --diff-file path/to/diff.txt [--approach summaries|full]
  python select_tests.py --repo ... --base master --head HEAD --two-stage

Behavior:
  - Successful API + empty or unparseable model reply → no tests selected.
  - API / transport failure → fall back to all discovered spec files (safe default).
  - last_model_response.txt = final selected paths (one per line, or "(none)"); last_model_raw_response.txt
    = raw assistant text (Stage 2 in --two-stage, full reply in single-shot).
  - --two-stage: Stage 1 = wide-net candidates; Stage 2 = final pick (precision default, --stage2-balanced,
    or --stage2-recall). last_stage2_merged_paths.txt = merge-only paths.
"""

