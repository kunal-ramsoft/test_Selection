# Checkpoint 3: Discover Playwright specs (paths relative to playwright/)
# Glob: Worklist-2/playwright/**/*.spec.js — sorted for stable order.
# Summaries are loaded from test_summaries.json (generated by generate_summaries.py).
# Optional snapshot: ../playwright_spec_paths.txt (documentation only; not read by scripts).
# ---------------------------------------------------------------------------
def playwright_dir(repo_path: Path) -> Path:
    """Absolute path to Worklist-2/playwright for a mono repo root."""
    return repo_path / "Worklist-2" / "playwright"


def discover_playwright_spec_paths(repo_path: Path) -> list[str]:
    """
    Return all *.spec.js paths under Worklist-2/playwright, relative to that folder,
    using forward slashes, sorted lexicographically.
    """
    root = playwright_dir(repo_path)
    if not root.is_dir():
        return []
    out: list[str] = []
    for p in sorted(root.rglob("*.spec.js")):
        rel = p.relative_to(root)
        out.append(str(rel).replace("\\", "/"))
    return out


def _summaries_json_path() -> Path:
    """Path to test_summaries.json (next to this script)."""
    return Path(__file__).resolve().parent / "test_summaries.json"


def get_test_summaries(repo_path: Path) -> list[tuple[str, str]]:
    """
    Return list of (path, one_line_summary) for Approach A.
    Loads from test_summaries.json; use generate_summaries.py to create/update it.
    Missing file or missing key -> "No summary".
    """
    import json
    paths = discover_playwright_spec_paths(repo_path)
    json_path = _summaries_json_path()
    if not json_path.exists():
        print("Note: test_summaries.json not found. Run generate_summaries.py first.", file=sys.stderr)
        return [(path, "No summary") for path in paths]
    try:
        data = json.loads(json_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        print(f"Warning: could not load {json_path}: {e}", file=sys.stderr)
        return [(path, "No summary") for path in paths]
    return [(path, data.get(path, "No summary")) for path in paths]


def get_test_full_contents(repo_path: Path) -> list[tuple[str, str]]:
    """Return list of (path, full_file_content) for Approach B. Skips missing files with a warning."""
    results = []
    pw_dir = playwright_dir(repo_path)
    for path in discover_playwright_spec_paths(repo_path):
        full_path = pw_dir / path
        if not full_path.exists():
            print(f"Warning: test file not found: {full_path}", file=sys.stderr)
            continue
        try:
            content = full_path.read_text(encoding="utf-8", errors="replace")
            results.append((path, content))
        except OSError as e:
            print(f"Warning: could not read {full_path}: {e}", file=sys.stderr)
    return results


def get_available_tests(repo_path: Path, approach: str) -> list[tuple[str, str]]:
    """
    Return list of (path, text) for all discovered *.spec.js tests.
    - approach "summaries": text = one-line summary from test_summaries.json.
    - approach "full": text = full spec file content (read from repo_path/Worklist-2/playwright/).
    """
    if approach == "summaries":
        return get_test_summaries(repo_path)
    if approach == "full":
        return get_test_full_contents(repo_path)
    raise ValueError(f"Unknown approach: {approach}")


def resolve_repo_path(repo_arg: str) -> Path:
    """Resolve repo path to absolute. Relative paths are relative to cwd."""
    p = Path(repo_arg)
    if not p.is_absolute():
        p = Path.cwd() / p
    return p.resolve()


def run_git(repo_path: Path, *args: str) -> str:
    """Run git in repo_path with given args. Returns stdout. Raises on non-zero exit."""
    cmd = ["git", *args]
    result = subprocess.run(
        cmd,
        cwd=repo_path,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr or result.stdout}")
    return result.stdout


def parse_diff_git_paths(diff_text: str) -> list[str]:
    """Extract changed file paths from 'diff --git a/path b/path' lines."""
    paths = []
    for m in re.finditer(r"^diff --git a/(.+?) b/.+", diff_text, re.MULTILINE):
        path = m.group(1).strip()
        if path and path not in paths:
            paths.append(path)
    return paths


