def parse_and_validate_response(model_response: str, allowed_paths: set[str]) -> list[str]:
    """
    Parse the model's reply into a list of test paths. Validates against allowed_paths.
    Returns [] if empty or no valid paths (no tests to run).
    Preserves first-seen order; drops duplicates.
    API errors are handled in main() with a separate fallback to all tests.
    """
    lines = [line.strip() for line in model_response.splitlines() if line.strip()]
    paths: list[str] = []
    seen: set[str] = set()
    for line in lines:
        # If model returned "path — summary" or "path: summary", take path only
        for sep in (" — ", ": "):
            if sep in line:
                line = line.split(sep)[0].strip()
                break
        # Strip common markdown bullet prefixes
        if line.startswith(("- ", "* ", "• ")):
            line = line[2:].strip()
        # Normalize path separators to forward slash
        path = line.replace("\\", "/")
        if path in allowed_paths and path not in seen:
            seen.add(path)
            paths.append(path)
    return paths


def _spec_basename_lower(path: str) -> str:
    """Filename only, lowercased, .spec.js stripped."""
    name = path.replace("\\", "/").split("/")[-1]
    return name.replace(".spec.js", "").lower()


def _diff_words_for_merge(full_diff: str | None) -> set[str]:
    """Words of length >= 4 from the diff (lowercase), for alignment checks."""
    if not full_diff or not full_diff.strip():
        return set()
    return {m.lower() for m in re.findall(r"[A-Za-z]{4,}", full_diff)}


def _should_merge_stage1_candidate(
    candidate_path: str,
    diff_words: set[str],
    changed_blob: str,
) -> bool:
    """
    True if this Stage-1 candidate should be unioned with Stage 2 output because it is
    strongly aligned with the diff text and changed file path (reduces dropped specific specs).
    Conservative: avoids merging unrelated toolbar specs unless rules match.
    """
    cl = candidate_path.lower()
    base = _spec_basename_lower(candidate_path)
    diff_hits = sum(1 for w in diff_words if len(w) >= 4 and w in cl)
    if diff_hits < 2:
        return False

    changed_blob = changed_blob.lower()

    # Change under wheel / tools.js: prefer specs whose basename names a tool or wheel
    if "wheel" in changed_blob or "tools.js" in changed_blob:
        if "tool" in base or "wheel" in base:
            return True

    # Window/level tool files: basename should contain window, level, and tool (e.g. windowLevelTool.spec.js)
    if "window" in base and "level" in base and "tool" in base:
        return True

    return False


def _should_merge_datagrid_worklist_selection(
    changed_files: list[str],
    full_diff: str | None,
    candidate_path: str,
) -> bool:
    """
    Merge WorklistSelection/worklistSelection.spec.js when DataGrid changes include data-cy / worklist table hooks.
    Reduces confusion with WorklistSelector when Stage 2 picks the wrong spec.
    """
    if not full_diff:
        return False
    if not any("datagrid.jsx" in f.replace("\\", "/").lower() for f in changed_files):
        return False
    dl = full_diff.lower()
    if not ("data-cy" in dl or "worklist-study" in dl or "study-status" in dl):
        return False
    cap = candidate_path.replace("\\", "/").lower()
    return cap == "worklistselection/worklistselection.spec.js" or cap.endswith(
        "/worklistselection.spec.js"
    )


def _should_merge_org_user_login_email(
    changed_files: list[str],
    full_diff: str | None,
    candidate_path: str,
) -> bool:
    """
    Merge User/disableLoginEmail.spec.js when OrganizationUser.jsx changes mention login/email copy.
    Helps multi-file diffs where Stage 2 keeps only worklist-related specs.
    """
    if not full_diff:
        return False
    if not any("organizationuser.jsx" in f.replace("\\", "/").lower() for f in changed_files):
        return False
    dl = full_diff.lower()
    if "login" not in dl and "email" not in dl:
        return False
    cap = candidate_path.replace("\\", "/").lower()
    return cap.endswith("/disableloginemail.spec.js")


def merge_stage2_with_stage1_path_alignment(
    stage2_paths: list[str],
    stage1_candidates: list[str],
    changed_files: list[str],
    full_diff: str | None,
    *,
    allowed_candidates: set[str],
) -> tuple[list[str], list[str]]:
    """
    Union Stage 2 paths with Stage-1 candidates that pass _should_merge_stage1_candidate.
    Only considers candidates in allowed_candidates (e.g. specs we could load for Stage 2).
    Returns (merged_paths, boosted_paths_only) where boosted are those not in stage2_paths.
    Preserves order: Stage 2 order first, then boosted in stage1 order.
    """
    diff_words = _diff_words_for_merge(full_diff)
    changed_blob = " ".join(changed_files)
    s2 = set(stage2_paths)
    out = list(stage2_paths)
    boosted: list[str] = []
    for c in stage1_candidates:
        if c not in allowed_candidates:
            continue
        if c in s2:
            continue
        if _should_merge_stage1_candidate(c, diff_words, changed_blob):
            out.append(c)
            s2.add(c)
            boosted.append(c)
        elif _should_merge_datagrid_worklist_selection(changed_files, full_diff, c):
            out.append(c)
            s2.add(c)
            boosted.append(c)
        elif _should_merge_org_user_login_email(changed_files, full_diff, c):
            out.append(c)
            s2.add(c)
            boosted.append(c)
    return out, boosted


def get_changed_files_and_diff(args) -> tuple[list[str], str | None]:
    """
    Return (changed_file_paths, full_diff_text).
    full_diff_text is None when using --diff-file only for name-only style parsing.
    """
    if args.diff_file:
        diff_path = Path(args.diff_file)
        if not diff_path.is_absolute():
            diff_path = Path.cwd() / diff_path
        if not diff_path.exists():
            raise FileNotFoundError(f"Diff file not found: {diff_path}")
        full_diff = diff_path.read_text(encoding="utf-8", errors="replace")
        changed = parse_diff_git_paths(full_diff)
        return changed, full_diff

    repo_path = resolve_repo_path(args.repo)
    if not repo_path.is_dir():
        raise NotADirectoryError(f"Repo path is not a directory: {repo_path}")

    # Changed file names (one per line)
    name_only = run_git(repo_path, "diff", args.base, args.head, "--name-only")
    changed = [line.strip() for line in name_only.splitlines() if line.strip()]

    # Full diff for prompt (optional)
    full_diff = run_git(repo_path, "diff", args.base, args.head)
    return changed, full_diff if full_diff.strip() else None


def write_final_selected_paths(path: Path, paths: list[str]) -> None:
    """Write last_model_response.txt: one spec path per line, or (none) if empty."""
    if not paths:
        path.write_text("(none)\n", encoding="utf-8")
    else:
        path.write_text("\n".join(paths) + "\n", encoding="utf-8")


def print_playwright_command(selected_paths: list[str]) -> None:
    """Print suggested npx line from Worklist-2."""
    if selected_paths:
        cmd_paths = " ".join(f"playwright/{p}" for p in selected_paths)
        print(f"\nRun from OmegaAI-Mono/Worklist-2:\n  npx playwright test {cmd_paths}")
    else:
        print("\nRun from OmegaAI-Mono/Worklist-2:\n  (no tests selected — no npx command)")


def run_two_stage_flow(
    args: argparse.Namespace,
    repo_path: Path,
    playwright_paths: list[str],
    allowed_set: set[str],
    changed_files: list[str],
    full_diff: str | None,
) -> None:
    """
    Stage 1: summaries → wide-net candidate paths.
    Stage 2: truncated spec bodies for candidates → final paths (precision-first unless --stage2-recall).
    last_model_response.txt = final selected paths (one per line); raw Stage 2 → last_model_raw_response.txt.
    """
    scripts_dir = Path(__file__).resolve().parent
    stage1_artifact = scripts_dir / "last_stage1_candidates.txt"
    out_file = scripts_dir / "last_model_response.txt"
    raw_response_file = scripts_dir / "last_model_raw_response.txt"
    merged_paths_file = scripts_dir / "last_stage2_merged_paths.txt"

    log_step("two-stage flow start", f"changed_files={len(changed_files)}, dry_run={args.dry_run}")

    available_tests = get_test_summaries(repo_path)
    print(f"\nTwo-stage: Stage 1 — path + summary for {len(available_tests)} spec(s).")

    s1_sys, s1_user = build_stage1_candidate_prompt(changed_files, full_diff, available_tests)
    log_step("Stage 1 prompt ready", f"system={len(s1_sys)} user={len(s1_user)} chars")
    print(f"\nStage 1 prompt: system={len(s1_sys)} chars, user={len(s1_user)} chars")
    print("Stage 1 user preview (first 400 chars):")
    print(s1_user[:400] + ("..." if len(s1_user) > 400 else ""))

    selected_paths: list[str] = []

    if args.dry_run:
        print("\n(dry-run: skipping Stage 1 & 2 Azure calls.)")
        print(
            "Stage 2 builds its prompt after Stage 1 returns candidate paths "
            "(truncated spec snippets per candidate).",
            file=sys.stderr,
        )
        print("\nSelected tests:\n  (dry-run — none)")
        print_playwright_command([])
        return

    # --- Stage 1 ---
    try:
        log_step("Stage 1", "calling Azure OpenAI (wide-net candidates)")
        r1 = call_azure_openai_for_selection(
            s1_sys,
            s1_user,
            max_completion_tokens=_stage1_max_completion_tokens(),
            log_label="Stage 1",
        )
    except RuntimeError as e:
        print(f"Warning: {e}", file=sys.stderr)
        print(
            "Falling back to all tests (safe default when the API call fails).",
            file=sys.stderr,
        )
        stage1_artifact.write_text(f"(Stage 1 API error — fallback to all tests)\n{e}", encoding="utf-8")
        raw_response_file.write_text(f"(Stage 1 API error — no Stage 2)\n{e}", encoding="utf-8")
        selected_paths = list(playwright_paths)
        write_final_selected_paths(out_file, selected_paths)
        print(f"\nFinal paths written to: {out_file}", file=sys.stderr)
        print(f"\nStage 1 raw response written to: {stage1_artifact}", file=sys.stderr)
        print("\nStage 1 model response: (not available — API error)")
        print("\nSelected tests:")
        for p in selected_paths:
            print(f"  {p}")
        print_playwright_command(selected_paths)
        return

    stage1_artifact.write_text(r1 or "(empty)", encoding="utf-8")
    print(f"\nStage 1 raw response written to: {stage1_artifact}", file=sys.stderr)
    print(f"\nStage 1 model response ({len(r1 or '')} chars):")
    print(r1 or "(empty)")

    candidates = parse_and_validate_response(r1 or "", allowed_set)
    log_step(
        "Stage 1 parse + validate",
        f"{len(candidates)} path(s) matched allowlist (empty model text or no valid lines → 0)",
    )
    if not candidates:
        raw_response_file.write_text(
            f"(Stage 1 returned no valid candidate paths — skipping Stage 2)\n{r1 or '(empty)'}",
            encoding="utf-8",
        )
        write_final_selected_paths(out_file, [])
        print(f"\nFinal paths written to: {out_file}", file=sys.stderr)
        print(f"Raw / status written to: {raw_response_file}", file=sys.stderr)
        print(
            "\nNote: No valid paths after Stage 1 — no tests selected.",
            file=sys.stderr,
        )
        print("\nSelected tests:\n  (none)")
        print_playwright_command([])
        return

    if args.stage2_recall:
        stage2_mode = "recall"
    elif getattr(args, "stage2_balanced", False):
        stage2_mode = "balanced"
    else:
        stage2_mode = "precision"
    _s2_mode_label = {
        "precision": "precision-first (default)",
        "balanced": "balanced (--stage2-balanced: slightly wider than precision)",
        "recall": "recall-first (--stage2-recall)",
    }[stage2_mode]
    print(f"\nStage 2 prompt mode: {_s2_mode_label}", file=sys.stderr)

    s2_cap = stage2_per_spec_max_chars(len(candidates))
    budget = _stage2_total_snippet_budget_chars()
    print(
        f"\nStage 2 snippet budget: total={budget} chars across {len(candidates)} candidate(s) "
        f"→ max {s2_cap} chars/spec (STAGE2_SPEC_MAX_CHARS={STAGE2_SPEC_MAX_CHARS} upper bound).",
        file=sys.stderr,
    )
    if s2_cap < STAGE2_SPEC_MAX_CHARS:
        print(
            "Stage 2: per-spec snippets reduced so the prompt stays smaller — avoids empty model "
            "replies on very large Stage-2 prompts. Override with STAGE2_MAX_TOTAL_SNIPPET_CHARS in .env.",
            file=sys.stderr,
        )

    log_step("Stage 2 load spec snippets", f"reading {len(candidates)} candidate file(s) from repo")
    snippets = get_truncated_spec_snippets(repo_path, candidates, max_chars=s2_cap)
    allowed_stage2 = {p for p, _ in snippets}
    log_step("Stage 2 snippets loaded", f"{len(snippets)} snippet(s), allowed_stage2={len(allowed_stage2)}")
    if not snippets:
        raw_response_file.write_text(
            "(Stage 2 skipped: no readable spec files for Stage-1 candidates.)",
            encoding="utf-8",
        )
        write_final_selected_paths(out_file, [])
        print(f"\nFinal paths written to: {out_file}", file=sys.stderr)
        print(
            "\nWarning: Could not read any candidate spec files for Stage 2.",
            file=sys.stderr,
        )
        print("\nSelected tests:\n  (none)")
        print_playwright_command([])
        return

    s2_sys, s2_user = build_stage2_final_prompt(
        changed_files, full_diff, snippets, stage2_mode=stage2_mode
    )
    log_step("Stage 2 prompt ready", f"system={len(s2_sys)} user={len(s2_user)} chars")
    if len(s2_user) > 150_000:
        print(
            f"\nWarning: Stage 2 user message is very large ({len(s2_user)} chars). "
            "If the model returns empty content, lower STAGE2_MAX_TOTAL_SNIPPET_CHARS or reduce Stage 1 recall.",
            file=sys.stderr,
        )
    print(f"\nStage 2 prompt: system={len(s2_sys)} chars, user={len(s2_user)} chars")
    print("Stage 2 user preview (first 400 chars):")
    print(s2_user[:400] + ("..." if len(s2_user) > 400 else ""))

    try:
        log_step("Stage 2", "calling Azure OpenAI (final path list from snippets)")
        r2 = call_azure_openai_for_selection(
            s2_sys,
            s2_user,
            max_completion_tokens=_stage2_max_completion_tokens(),
            log_label="Stage 2",
        )
    except RuntimeError as e:
        print(f"Warning: {e}", file=sys.stderr)
        print(
            "Falling back to all tests (safe default when the API call fails).",
            file=sys.stderr,
        )
        raw_response_file.write_text(f"(Stage 2 API error — fallback to all tests)\n{e}", encoding="utf-8")
        selected_paths = list(playwright_paths)
        write_final_selected_paths(out_file, selected_paths)
        print(f"\nFinal paths written to: {out_file}", file=sys.stderr)
        print("\nStage 2 model response: (not available — API error)")
        print("\nSelected tests:")
        for p in selected_paths:
            print(f"  {p}")
        print_playwright_command(selected_paths)
        return

    raw_response_file.write_text(r2 or "(empty)", encoding="utf-8")
    print(f"\nRaw Stage 2 response written to: {raw_response_file}", file=sys.stderr)
    print(f"\nStage 2 model response ({len(r2 or '')} chars):")
    print(r2 or "(empty)")

    selected_paths = parse_and_validate_response(r2 or "", allowed_stage2)
    log_step(
        "Stage 2 parse + validate",
        f"{len(selected_paths)} path(s) after parse (empty Stage 2 text → 0)",
    )

    boosted: list[str] = []
    if stage2_mode != "recall":
        log_step("Stage 2 merge with Stage 1", "path-alignment heuristics")
        selected_paths, boosted = merge_stage2_with_stage1_path_alignment(
            selected_paths,
            candidates,
            changed_files,
            full_diff,
            allowed_candidates=allowed_stage2,
        )
        log_step("Stage 2 merge done", f"final count={len(selected_paths)}, boosted={len(boosted)}")
        if boosted:
            print(
                f"\nMerged {len(boosted)} Stage-1 path(s) (diff/path alignment): {', '.join(boosted)}",
                file=sys.stderr,
            )
            merged_paths_file.write_text("\n".join(boosted) + "\n", encoding="utf-8")
            print(f"Merged paths written to: {merged_paths_file}", file=sys.stderr)
        else:
            merged_paths_file.write_text("(none)\n", encoding="utf-8")
    else:
        merged_paths_file.write_text("(merge skipped: Stage 2 recall mode)\n", encoding="utf-8")

    if (
        not selected_paths
        and not (r2 or "").strip()
        and candidates
        and os.environ.get("STAGE2_FALLBACK_STAGE1", "").strip().lower() in ("1", "true", "yes")
    ):
        selected_paths = [p for p in candidates if p in allowed_stage2]
        log_step(
            "STAGE2_FALLBACK_STAGE1",
            f"using {len(selected_paths)} Stage-1 path(s) because Stage 2 output was empty",
        )
        print(
            f"\nStage 2 empty — STAGE2_FALLBACK_STAGE1: using {len(selected_paths)} path(s) from Stage 1 "
            "(set STAGE2_FALLBACK_STAGE1=0 to disable).",
            file=sys.stderr,
        )

    write_final_selected_paths(out_file, selected_paths)
    print(f"\nFinal paths written to: {out_file}", file=sys.stderr)

    if not selected_paths:
        if not (r2 or "").strip():
            print(
                "\nNote: Stage 2 returned empty content — no tests selected.",
                file=sys.stderr,
            )
        else:
            print(
                "\nNote: Stage 2 reply had no valid test paths — no tests selected.",
                file=sys.stderr,
            )

    print("\nSelected tests:")
    if not selected_paths:
        print("  (none)")
    else:
        for p in selected_paths:
            print(f"  {p}")
    log_step("two-stage flow complete", f"final selected_paths={len(selected_paths)}")
    print_playwright_command(selected_paths)


def main():
    parser = argparse.ArgumentParser(description="Select E2E tests to run based on code diff via Azure OpenAI.")
    parser.add_argument("--repo", default="../OmegaAI-Mono", help="Path to OmegaAI-Mono repo root")
    parser.add_argument("--base", default="master", help="Base ref for git diff")
    parser.add_argument("--head", default="HEAD", help="Head ref for git diff")
    parser.add_argument("--diff-file", help="Path to pre-saved diff file (optional, instead of base/head)")
    parser.add_argument("--approach", choices=("summaries", "full"), default="summaries",
                        help="summaries = path + one-line summary per test; full = full spec file content")
    parser.add_argument("--dry-run", action="store_true",
                        help="build prompt but do not call Azure OpenAI (no API key needed)")
    parser.add_argument(
        "--two-stage",
        action="store_true",
        help=(
            "Two-step selection: Stage 1 = wide-net candidates from summaries; Stage 2 = final paths "
            "using truncated spec bodies (precision-first by default). Single-shot (default) uses --approach."
        ),
    )
    parser.add_argument(
        "--stage2-recall",
        action="store_true",
        help=(
            "With --two-stage only: Stage 2 recall-first (keep every plausible candidate). "
            "Mutually exclusive with --stage2-balanced."
        ),
    )
    parser.add_argument(
        "--stage2-balanced",
        action="store_true",
        help=(
            "With --two-stage only: Stage 2 balanced mode — slightly more tests than precision-default "
            "(e.g. 2–5 paths when several distinct flows apply). Mutually exclusive with --stage2-recall."
        ),
    )
    args = parser.parse_args()

    if args.stage2_recall and not args.two_stage:
        print("Error: --stage2-recall requires --two-stage.", file=sys.stderr)
        sys.exit(1)
    if args.stage2_balanced and not args.two_stage:
        print("Error: --stage2-balanced requires --two-stage.", file=sys.stderr)
        sys.exit(1)
    if args.stage2_recall and args.stage2_balanced:
        print("Error: use only one of --stage2-recall or --stage2-balanced.", file=sys.stderr)
        sys.exit(1)

    # Avoid UnicodeEncodeError on Windows (cp1252) when printing summaries with special chars
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            try:
                stream.reconfigure(encoding="utf-8", errors="replace")
            except Exception:
                pass

    repo_path = resolve_repo_path(args.repo)
    if not repo_path.is_dir():
        print(f"Error: repo path is not a directory: {repo_path}", file=sys.stderr)
        sys.exit(1)

    playwright_paths = discover_playwright_spec_paths(repo_path)
    if not playwright_paths:
        print(
            f"Error: no *.spec.js files under {playwright_dir(repo_path)}",
            file=sys.stderr,
        )
        sys.exit(1)
    allowed_set = set(playwright_paths)

    try:
        changed_files, full_diff = get_changed_files_and_diff(args)
    except (RuntimeError, FileNotFoundError, NotADirectoryError) as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)

    log_step(
        "git diff loaded",
        f"{len(changed_files)} file(s), diff_len={len(full_diff) if full_diff else 0}",
    )

    # Checkpoint 2: output for verification
    print(f"Discovered {len(playwright_paths)} Playwright spec(s) under Worklist-2/playwright.")
    print("Changed files:")
    for p in changed_files:
        print(f"  {p}")
    if full_diff is not None:
        print(f"\nFull diff length: {len(full_diff)} chars")
    else:
        print("\nFull diff: (none captured)")

    if args.two_stage:
        if args.approach != "summaries":
            print(
                "Note: --two-stage uses summaries for Stage 1 and spec snippets for Stage 2; "
                "--approach is ignored.",
                file=sys.stderr,
            )
        run_two_stage_flow(args, repo_path, playwright_paths, allowed_set, changed_files, full_diff)
        return

    # Checkpoint 3: available tests (summaries or full content per --approach)
    try:
        available_tests = get_available_tests(repo_path, args.approach)
    except (ValueError, NotADirectoryError) as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
    log_step("available tests loaded", f"approach={args.approach}, count={len(available_tests)}")
    print(f"\nAvailable tests (approach={args.approach}):")
    for path, text in available_tests:
        preview = text[:80] + "..." if len(text) > 80 else text
        print(f"  {path}: {preview!r}")

    # Checkpoint 4: build prompt for AI
    system_msg, user_msg = build_prompt(changed_files, full_diff, available_tests)
    log_step("single-shot prompt built", f"system={len(system_msg)} user={len(user_msg)} chars")
    print(f"\nPrompt built: system={len(system_msg)} chars, user={len(user_msg)} chars")
    print("User message preview (first 400 chars):")
    print(user_msg[:400] + ("..." if len(user_msg) > 400 else ""))

    # Checkpoint 5: call Azure OpenAI for test selection
    if args.dry_run:
        log_step("single-shot", "dry-run — skipping Azure OpenAI")
        print("\n(dry-run: skipping Azure OpenAI call)")
    else:
        _scripts_dir = Path(__file__).resolve().parent
        _out_file = _scripts_dir / "last_model_response.txt"
        _raw_file = _scripts_dir / "last_model_raw_response.txt"
        selected_paths: list[str] = []
        try:
            log_step("single-shot", "calling Azure OpenAI")
            model_response = call_azure_openai_for_selection(
                system_msg,
                user_msg,
                max_completion_tokens=_default_max_completion_tokens(),
                log_label="single-shot",
            )
        except RuntimeError as e:
            # API / transport failure: safe default is run all tests
            print(f"Warning: {e}", file=sys.stderr)
            print(
                "Falling back to all tests (safe default when the API call fails).",
                file=sys.stderr,
            )
            _raw_file.write_text(f"(API error — fallback to all tests)\n{e}", encoding="utf-8")
            selected_paths = list(playwright_paths)
            write_final_selected_paths(_out_file, selected_paths)
            print(f"\nRaw assistant text written to: {_raw_file}", file=sys.stderr)
            print(f"\nFinal paths written to: {_out_file}", file=sys.stderr)
            print("\nModel response: (not available — API error)")
        else:
            print(f"\nModel response ({len(model_response)} chars):")
            print(model_response or "(empty)")

            _raw_file.write_text(model_response or "(empty)", encoding="utf-8")
            print(f"\nRaw assistant text written to: {_raw_file}", file=sys.stderr)

            # Successful API: empty or unparseable reply → no tests (not all tests)
            selected_paths = parse_and_validate_response(model_response, allowed_set)
            log_step(
                "single-shot parse + validate",
                f"{len(selected_paths)} path(s) (empty reply or unknown paths → 0)",
            )
            write_final_selected_paths(_out_file, selected_paths)
            print(f"\nFinal paths written to: {_out_file}", file=sys.stderr)
            if not selected_paths:
                if not (model_response or "").strip():
                    print(
                        "\nNote: Model returned empty content — no tests selected.",
                        file=sys.stderr,
                    )
                else:
                    print(
                        "\nNote: Model reply had no valid test paths (e.g. none required) — no tests selected.",
                        file=sys.stderr,
                    )

        log_step("single-shot flow complete", f"final selected_paths={len(selected_paths)}")
        print("\nSelected tests:")
        if not selected_paths:
            print("  (none)")
        else:
            for p in selected_paths:
                print(f"  {p}")
        print_playwright_command(selected_paths)


if __name__ == "__main__":
    main()
