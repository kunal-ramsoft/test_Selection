MAX_DIFF_CHARS = 12_000  # Truncate diff to avoid token limits
# Stage 2: per-spec truncation (same order of magnitude as generate_summaries.py's 8000)
STAGE2_SPEC_MAX_CHARS = 10_000
# Stage 2: cap total snippet size across all Stage-1 candidates. Without this, many candidates × 10k
# chars explodes the prompt (~60k+ tokens) and models like gpt-5-mini often return empty message.content.
STAGE2_TOTAL_SNIPPET_BUDGET_CHARS_DEFAULT = 100_000
STAGE2_PER_SPEC_FLOOR_CHARS = 200  # minimum per spec when budget is tight (still truncated)


def _default_max_completion_tokens() -> int:
    return int(os.environ.get("AZURE_OPENAI_SELECTION_MAX_COMPLETION_TOKENS", "8192"))


def _stage1_max_completion_tokens() -> int:
    return int(os.environ.get("AZURE_OPENAI_STAGE1_MAX_COMPLETION_TOKENS", "16384"))


def _stage2_max_completion_tokens() -> int:
    # Reasoning models charge reasoning_tokens inside completion_tokens; default must leave room
    # for paths after reasoning (see completion_tokens_details in logs).
    return int(os.environ.get("AZURE_OPENAI_STAGE2_MAX_COMPLETION_TOKENS", "16384"))


def _stage2_total_snippet_budget_chars() -> int:
    return int(
        os.environ.get(
            "STAGE2_MAX_TOTAL_SNIPPET_CHARS",
            str(STAGE2_TOTAL_SNIPPET_BUDGET_CHARS_DEFAULT),
        )
    )


def stage2_per_spec_max_chars(num_candidates: int) -> int:
    """
    Per-spec char cap for Stage 2 so total snippets stay within STAGE2_MAX_TOTAL_SNIPPET_CHARS.
    When Stage 1 returns many paths, each spec gets less than STAGE2_SPEC_MAX_CHARS automatically.
    """
    if num_candidates <= 0:
        return STAGE2_SPEC_MAX_CHARS
    budget = _stage2_total_snippet_budget_chars()
    per = budget // num_candidates
    per = max(STAGE2_PER_SPEC_FLOOR_CHARS, per)
    return min(STAGE2_SPEC_MAX_CHARS, per)


def build_prompt(
    changed_files: list[str],
    full_diff: str | None,
    available_tests: list[tuple[str, str]],
) -> tuple[str, str]:
    """
    Build system and user messages for the test-selection AI.
    Returns (system_message, user_message).
    """
    system_message = (
        "You are a test-selection assistant. You are given a code change (changed files and optionally a diff) "
        "and a list of **Available tests** (each entry: path + short description of what that E2E test covers). "
        "Your job is to pick which of those tests should run for this change.\n\n"
        "Rules (same whether there are few or many tests):\n"
        "1. **Minimum set**: Include only tests you can justify from the changed paths and diff. Do not add tests "
        "\"to be safe,\" for broad product familiarity, or because areas feel loosely related.\n"
        "2. **Evidence**: For every path you output, there must be a clear link between the change and that test's "
        "description in the Available tests list (file paths, feature names, UI strings, or behavior visible in the diff).\n"
        "3. **Shared components**: Changes to shared UI (tables, grids, layout, generic components) may affect many "
        "features. Select a test only if **that test's description** matches what this change plausibly affects. "
        "Do **not** select tests for unrelated feature areas just because they also use a shared component elsewhere "
        "in the app.\n"
        "4. **Use the list**: The Available tests section is the source of truth for paths and scope. Rely on each "
        "line's description to decide fit; do not invent paths.\n\n"
        "Output format: reply with **only** the test file paths from the Available tests list, **one path per line**, "
        "using the **exact** path strings shown. No explanations, bullets, markdown, or other text. "
        "If no listed test is justified, reply with **no lines** (empty response)."
    )

    parts = ["Changed files:"]
    for p in changed_files:
        parts.append(f"  {p}")
    parts.append("")

    if full_diff and full_diff.strip():
        diff_text = full_diff.strip()
        if len(diff_text) > MAX_DIFF_CHARS:
            diff_text = diff_text[:MAX_DIFF_CHARS] + "\n\n... (diff truncated)"
            parts.append("Diff (truncated):")
        else:
            parts.append("Diff:")
        parts.append(diff_text)
        parts.append("")
    else:
        parts.append("Diff: (none)")
        parts.append("")

    parts.append("Available tests:")
    for path, text in available_tests:
        # Use path exactly as returned by discover_playwright_spec_paths for consistent parsing
        if len(text) > 500:
            parts.append(f"  {path}:")
            parts.append(text[:500] + "\n... (content truncated)")
        else:
            parts.append(f"  {path} — {text}")
    parts.append("")
    parts.append(
        "Which of the above tests are **directly** justified by this change? Reply with only those paths, "
        "one per line, no other text. Prefer the smallest sufficient set; use each test's description to "
        "match scope to the change. If none apply, reply with nothing."
    )

    user_message = "\n".join(parts)
    return system_message, user_message


def build_stage1_candidate_prompt(
    changed_files: list[str],
    full_diff: str | None,
    available_tests: list[tuple[str, str]],
) -> tuple[str, str]:
    """
    Stage 1 — recall-focused candidate list from paths + summaries only.
    Model chooses how many paths to include (no fixed cap); cast a wide net.
    """
    system_message = (
        "You are a **candidate-generation** assistant for E2E test selection.\n\n"
        "You are given a code change (changed files and optionally a diff) and **Available tests**: "
        "each line is a Playwright spec path plus a short summary of what that test covers.\n\n"
        "**Goal — recall first:** List **every** spec from Available tests that could **plausibly** be "
        "relevant to this change — including **borderline**, **indirect**, or **remotely connected** cases. "
        "Cast a **wide net**. Prefer **including** a spec when unsure rather than omitting it. "
        "This stage is **not** for finding the smallest set.\n\n"
        "Rules:\n"
        "- Output **only** paths that appear in the Available tests list, using the **exact** path strings.\n"
        "- **One path per line.** No explanations, bullets, markdown, numbering, or extra text.\n"
        "- Include **as many** plausible candidates as needed; **do not** limit yourself to a small number "
        "for brevity.\n"
        "- Do **not** invent paths.\n"
        "- If **nothing** in the list is even remotely related, reply with **no lines** (empty response)."
    )

    parts = ["Changed files:"]
    for p in changed_files:
        parts.append(f"  {p}")
    parts.append("")

    if full_diff and full_diff.strip():
        diff_text = full_diff.strip()
        if len(diff_text) > MAX_DIFF_CHARS:
            diff_text = diff_text[:MAX_DIFF_CHARS] + "\n\n... (diff truncated)"
            parts.append("Diff (truncated):")
        else:
            parts.append("Diff:")
        parts.append(diff_text)
        parts.append("")
    else:
        parts.append("Diff: (none)")
        parts.append("")

    parts.append("Available tests:")
    for path, text in available_tests:
        if len(text) > 500:
            parts.append(f"  {path}:")
            parts.append(text[:500] + "\n... (content truncated)")
        else:
            parts.append(f"  {path} — {text}")
    parts.append("")
    parts.append(
        "Reply with **only** the candidate test paths (wide net, recall-first), one per line, "
        "exact paths from the list above."
    )

    return system_message, "\n".join(parts)


def get_truncated_spec_snippets(
    repo_path: Path,
    paths: list[str],
    max_chars: int = STAGE2_SPEC_MAX_CHARS,
) -> list[tuple[str, str]]:
    """
    For each path, read spec under Worklist-2/playwright/<path> and truncate to max_chars.
    Skips missing files with a warning; order matches `paths`.
    """
    pw_dir = playwright_dir(repo_path)
    out: list[tuple[str, str]] = []
    for path in paths:
        full_path = pw_dir / path
        if not full_path.exists():
            print(f"Warning: test file not found for Stage 2: {full_path}", file=sys.stderr)
            continue
        try:
            content = full_path.read_text(encoding="utf-8", errors="replace")
        except OSError as e:
            print(f"Warning: could not read {full_path}: {e}", file=sys.stderr)
            continue
        if len(content) > max_chars:
            snippet = content[:max_chars] + "\n\n... (spec truncated)"
        else:
            snippet = content
        out.append((path, snippet))
    return out


def build_stage2_final_prompt(
    changed_files: list[str],
    full_diff: str | None,
    path_and_snippets: list[tuple[str, str]],
    *,
    stage2_mode: str = "precision",
) -> tuple[str, str]:
    """
    Stage 2 — final selection using changed files, diff, and truncated spec bodies for Stage-1 candidates only.

    stage2_mode:
      - ``precision`` — smallest necessary set (default).
      - ``balanced`` — slightly wider: 2–5 paths when several distinct flows plausibly apply.
      - ``recall`` — recall-first; keep every plausible candidate (legacy).
    """
    if stage2_mode == "recall":
        system_message = (
            "You are a **final test-selection** assistant for Playwright E2E tests.\n\n"
            "You are given the code change and **truncated contents** of candidate spec files (Stage 1 already "
            "narrowed the universe). Your job is to output the tests that should run for this change.\n\n"
            "**Recall first — do not minimize:** Include **every** spec whose path appears below if that test "
            "could **plausibly fail** or **needs validation** for this change. Do **not** omit a necessary test "
            "to shorten the list. **Extra** specs are acceptable when in doubt.\n\n"
            "Output **only** paths from the candidate set provided below (the paths shown before each snippet), "
            "using the **exact** path strings. **One path per line.** No explanations, bullets, markdown, or other text. "
            "If none of the candidates apply, reply with **no lines** (empty response)."
        )
        closing = (
            "Reply with **only** the paths to run, one per line (exact paths from the --- headers above). "
            "Recall-first: include every candidate that could plausibly need to run for this change."
        )
    elif stage2_mode == "balanced":
        system_message = (
            "You are a **final test-selection** assistant for Playwright E2E tests.\n\n"
            "You are given the code change and **truncated contents** of candidate spec files (Stage 1 already "
            "produced a broad list). Your job is to output a **small** set of tests — **slightly wider** than the "
            "bare minimum: allow **light** over-inclusion when several Stage-1 candidates cover **different** user "
            "flows or surfaces for the same product area.\n\n"
            "**Balanced — modest recall (not full Stage 1 list):**\n"
            "- Still **omit** candidates that are clearly unrelated to the diff.\n"
            "- If **multiple** Stage-1 paths sit under the **same product line** (e.g. shared prefix like `Blume/` "
            "or neighboring folders such as `BlumeHome/`, `BlumeForms/`, `BlumeDocuments/`) and the change is "
            "**non-trivial** (several changed files, assets, strings, or cross-cutting behavior), prefer **2–5** "
            "paths that each plausibly exercise a **distinct** flow — do **not** collapse to a single spec by default "
            "in that situation.\n"
            "- If **roughly five or more** files appear under Changed files, include **at least two** paths when "
            "at least two candidates each have a plausible link to the change.\n"
            "- When the diff clearly touches **only one** narrow behavior, **one** path is enough.\n"
            "- Do **not** output the entire Stage 1 candidate list unless most lines are genuinely justified.\n\n"
            "Output **only** paths from the candidate set below (paths before each `---` block), using the **exact** "
            "path strings. **One path per line.** No explanations, bullets, markdown, or other text. "
            "If none of the candidates are justified, reply with **no lines** (empty response)."
        )
        closing = (
            "Reply with **only** the paths to run, one per line (exact paths from the --- headers above). "
            "Balanced: a **small** set with **light** over-inclusion when several distinct flows apply."
        )
    else:
        system_message = (
            "You are a **final test-selection** assistant for Playwright E2E tests.\n\n"
            "You are given the code change and **truncated contents** of candidate spec files (Stage 1 already "
            "produced a broad candidate list). Your job is to output the **smallest sufficient** set of tests "
            "that should run for **this specific change**.\n\n"
            "**Precision — minimize false positives:**\n"
            "- Include a path **only** if this diff could plausibly cause that test to **fail**, or require "
            "an update, because of what the test **asserts or exercises** (selectors, visible text, tool names, "
            "feature behavior tied to the changed code).\n"
            "- Do **not** include tests merely because they belong to the same broad area (e.g. generic toolbar, "
            "viewer, or navigation) if the diff does **not** plausibly affect what those tests check.\n"
            "- For **small or localized** changes (e.g. a label, string, or single control), prefer **few** specs — "
            "often **one** — that directly cover that surface; do not add \"related\" specs for safety.\n"
            "- Include **more** paths only when the diff clearly spans multiple features, files, or behaviors.\n"
            "- **Specificity over breadth:** If Stage 1 listed a candidate whose **filename** clearly names the "
            "feature or control in the **changed file path** (e.g. `windowLevelTool.spec.js` for a change under "
            "`.../Wheel/tools.js` affecting window/level wording), **prefer that spec** over broader tests "
            "(generic toolbar, another wheel control, or \"nearby\" viewer tests) unless the diff clearly touches those.\n"
            "- **Do not drop** the most **specific** Stage-1 candidate that directly names the changed behavior "
            "in favor of a looser test that only partially overlaps.\n"
            "- **Multiple changed files:** If **two or more** different files appear under Changed files above, do **not** "
            "collapse the whole diff to a **single** test when distinct areas are affected (e.g. organization user "
            "copy vs shared DataGrid). Include **at least one** justified path per **changed file** (or per clearly "
            "distinct feature), unless an extra file is only a trivial rename with no test impact.\n"
            "- **DataGrid / `data-cy` / worklist table:** If the diff changes **`data-cy`**, **`Table`**, or **`DataGrid`** "
            "in worklist UI, prefer specs that cover **table behavior, row selection, or the study grid** — not only "
            "a loosely related \"worklist\" test with a similar name.\n"
            "- **Naming:** **WorklistSelection** (row selection, multi-select) vs **WorklistSelector** (which worklist / "
            "layout) are different features; pick the candidate whose **path and summary** match **what** the diff "
            "touches (table vs picker), not just the word \"worklist\".\n\n"
            "Output **only** paths from the candidate set below (paths before each `---` block), using the **exact** "
            "path strings. **One path per line.** No explanations, bullets, markdown, or other text. "
            "If none of the candidates are justified by this diff, reply with **no lines** (empty response)."
        )
        closing = (
            "Reply with **only** the paths to run, one per line (exact paths from the --- headers above). "
            "Smallest sufficient set for **this** diff — do not pad the list."
        )

    parts = ["Changed files:"]
    for p in changed_files:
        parts.append(f"  {p}")
    parts.append("")

    if full_diff and full_diff.strip():
        diff_text = full_diff.strip()
        if len(diff_text) > MAX_DIFF_CHARS:
            diff_text = diff_text[:MAX_DIFF_CHARS] + "\n\n... (diff truncated)"
            parts.append("Diff (truncated):")
        else:
            parts.append("Diff:")
        parts.append(diff_text)
        parts.append("")
    else:
        parts.append("Diff: (none)")
        parts.append("")

    parts.append("Candidate specs (path + truncated file content; paths are the only valid outputs):")
    for path, snippet in path_and_snippets:
        parts.append("")
        parts.append(f"--- {path} ---")
        parts.append(snippet)
    parts.append("")
    parts.append(closing)

    return system_message, "\n".join(parts)


